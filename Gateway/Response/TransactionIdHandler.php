declare(strict_types=1);

namespace Payone\CommercePlatform\Gateway\Response;

use Magento\Payment\Gateway\Response\HandlerInterface;
use Payone\CommercePlatform\Gateway\SubjectReader;

/**
 * Uses the PAYONE id of the capture/refund/cancel (e.g. "TX2AB0WM61F3CZ31") as Magento transaction id
 *
 * The id generated by Magento ("<payment id>-capture", "-refund") is identical for multiple partial captures/refunds.
 * Magento builds the transaction with this id after the command returned.
 * Capture and refund responses contain the id on the top level, cancel responses in the payment object.
 */
class TransactionIdHandler implements HandlerInterface
{
    /**
     * @param SubjectReader $subjectReader
     */
    public function __construct(
        private readonly SubjectReader $subjectReader,
    ) {
    }

    /**
     * Sets the transaction id on the payment
     *
     * @param array $handlingSubject
     * @param array $response
     * @return void
     */
    public function handle(array $handlingSubject, array $response): void
    {
        $body = $response['body'] ?? [];
        $operationId = $body['id'] ?? $body['payment']['id'] ?? null;
        if (!empty($operationId)) {
            $this->subjectReader->readPayment($handlingSubject)->getPayment()->setTransactionId((string)$operationId);
        }
    }
}
