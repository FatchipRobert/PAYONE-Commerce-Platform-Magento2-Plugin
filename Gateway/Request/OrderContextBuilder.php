declare(strict_types=1);

namespace Payone\CommercePlatform\Gateway\Request;

use Magento\Payment\Gateway\Request\BuilderInterface;
use Payone\CommercePlatform\Gateway\SubjectReader;

/**
 * Store and order data of every payment command: the store of the order for the credentials and environment,
 * order number and payment method for the API log
 */
class OrderContextBuilder implements BuilderInterface
{
    /**
     * @param SubjectReader $subjectReader
     */
    public function __construct(
        private readonly SubjectReader $subjectReader,
    ) {
    }

    /**
     * Builds the request part
     *
     * @param array $buildSubject
     * @return array
     */
    public function build(array $buildSubject): array
    {
        $payment = $this->subjectReader->readPayment($buildSubject)->getPayment();
        $order = $payment->getOrder();

        return [
            'store_id' => (int)$order->getStoreId(),
            'order_increment_id' => (string)$order->getIncrementId(),
            'payment_method' => (string)$payment->getMethod(),
        ];
    }
}
